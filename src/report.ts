import type { Gap, Location, ScanResult } from "./types.js";

const NOTE = "> Generated by DPDP Guard. Not legal advice: these are heuristic findings for engineers. Have a lawyer review the final register.";

const loc = (l: Location) => `\`${l.file}:${l.line}\``;

function locs(list: Location[], max = 3): string {
  if (list.length === 0) return "-";
  const shown = list.slice(0, max).map(loc).join("<br>");
  return list.length > max ? `${shown}<br>+${list.length - max} more` : shown;
}

const cell = (s: string) => s.replace(/\|/g, "\\|");

export function registerMarkdown(r: ScanResult): string {
  const out = [
    "# DPDP data register",
    "",
    NOTE,
    "",
    `Scanned \`${r.root}\` on ${r.generatedAt.slice(0, 10)}: ${r.filesScanned} files, ${r.register.length} data elements, ${r.gaps.length} gaps (see dpdp-gaps.md).`,
    "",
    "Fill in **Purpose** and **Retention** for every row. DPDP needs a clear, specific purpose for each element (Sec 5, 6).",
    "",
    "| Data element | Category | Collected at | Stored in | Shared with | Purpose | Retention |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const row of r.register) {
    const label = row.confidence === "medium" ? `${row.label} (maybe)` : row.label;
    const stored = row.storedIn.length ? row.storedIn.map((s) => `\`${s.ref}\``).join("<br>") : "-";
    out.push(`| ${cell(label)} | ${row.category} | ${locs(row.collectedAt)} | ${stored} | ${row.sharedWith.join(", ") || "-"} | ${row.purpose} | ${row.retention} |`);
  }
  if (r.register.length === 0) out.push("| _No personal data found_ | | | | | | |");

  out.push("", "## Third parties found in package.json", "");
  if (r.thirdParties.length === 0) out.push("None.");
  else {
    out.push("| Vendor | Kind | Package |", "|---|---|---|");
    for (const t of r.thirdParties) out.push(`| ${t.processor} | ${t.kind} | \`${t.pkg}\` |`);
    out.push("", "Each vendor that receives personal data is a Data Processor: you need a contract with it and must list it in your notice.");
  }
  return out.join("\n") + "\n";
}

export function gapsMarkdown(r: ScanResult): string {
  const count = (s: Gap["severity"]) => r.gaps.filter((g) => g.severity === s).length;
  const out = ["# DPDP gap report", "", NOTE, "", `**${count("high")} high, ${count("medium")} medium, ${count("low")} low**`, ""];
  if (r.gaps.length === 0) out.push("No gaps found by the current rules.");
  for (const g of r.gaps) {
    out.push(`## ${g.rule} · ${g.title} (${g.severity})`, "", `${loc(g)}`, "", g.message, "", `**Fix:** ${g.fix}`, "");
  }
  return out.join("\n");
}

export function summaryText(r: ScanResult): string {
  const lines = [`DPDP Guard: ${r.filesScanned} files, ${r.register.length} personal data elements, ${r.gaps.length} gaps`];
  for (const g of r.gaps.slice(0, 10)) lines.push(`  ${g.severity.padEnd(6)} ${g.rule} ${g.file}:${g.line}  ${g.title}`);
  if (r.gaps.length > 10) lines.push(`  ... ${r.gaps.length - 10} more in dpdp-gaps.md`);
  return lines.join("\n");
}

export const COMMENT_MARKER = "<!-- dpdp-guard -->";

/** Short PR comment for what a diff added. Empty string when nothing new. */
export function prCommentMarkdown(r: ScanResult): string {
  if (r.register.length === 0 && r.gaps.length === 0) return "";
  const out = [COMMENT_MARKER, "### DPDP Guard: new personal data in this PR", ""];
  if (r.register.length) {
    out.push("| Data element | Category | Where | Purpose |", "|---|---|---|---|");
    for (const row of r.register) {
      const where = [...row.collectedAt, ...row.storedIn].slice(0, 2).map(loc).join(", ") || "-";
      out.push(`| ${cell(row.label)} | ${row.category} | ${where} | ${cell(row.purpose)} |`);
    }
    out.push("", "Please add a purpose and retention for each new element to the data register.", "");
  }
  if (r.gaps.length) {
    out.push("**Gaps on changed lines**", "");
    for (const g of r.gaps) out.push(`- **${g.severity}** ${g.rule} ${g.title} at ${loc(g)}: ${g.message}`);
    out.push("");
  }
  out.push("<sub>Heuristic check, not legal advice.</sub>", "");
  return out.join("\n");
}
